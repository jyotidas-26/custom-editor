// Comparison Operators (Check Conditions)
// Used to compare two values and return true or false.

// Operator	Description	Example (a = 10, b = 5)	Result
// ==	Equal to	a == b	false
// ===	Strict equal (checks type too)	a === "10"	false
// !=	Not equal to	a != b	true
// !==	Strict not equal	a !== "10"	true
// >	Greater than	a > b	true
// <	Less than	a < b	false
// >=	Greater than or equal	a >= 10	true
// <=	Less than or equal	b <= 5	true

// &&	AND (Both must be true)	x && y	false
// `		`	OR (At least one true)
// !	NOT (Reverse value)	!x	false
